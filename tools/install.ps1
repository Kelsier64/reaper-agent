# install.ps1 - point REAPER at the bridge next to this script (<this folder>\..\bridge).
# Writes a tiny loader to %APPDATA%\REAPER\Scripts\ClaudeBridge\ClaudeBridge.lua that runs
# <root>\bridge\bridge.lua. Works the same from the dev repo (tools\) and from an installed
# skill (scripts\), because both keep bridge\ as a sibling folder.
# If the loader already points at a DIFFERENT bridge (e.g. the dev repo), nothing is changed
# unless -Force is given, so installing a skill never silently replaces a dev bridge.
# Then: node reaper.mjs restart (or start)
param([switch]$Force)
$ErrorActionPreference = 'Stop'
[Console]::OutputEncoding = [Text.Encoding]::UTF8
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$bridgeDir = Join-Path $root 'bridge'
if (-not (Test-Path (Join-Path $bridgeDir 'bridge.lua'))) { throw "bridge.lua not found in $bridgeDir" }
$base = Join-Path $env:APPDATA 'REAPER\Scripts\ClaudeBridge'
$loaderPath = Join-Path $base 'ClaudeBridge.lua'
$want = "$bridgeDir\"

if (Test-Path $loaderPath) {
  $cur = $null
  $m = [regex]::Match([IO.File]::ReadAllText($loaderPath), 'CLAUDE_BRIDGE_ROOT = \[\[(.*?)\]\]')
  if ($m.Success) { $cur = $m.Groups[1].Value }
  if ($cur -and ($cur.TrimEnd('\') -ne $want.TrimEnd('\')) -and -not $Force) {
    Write-Output ('{"ok":false,"installed":true,"current_root":' + (ConvertTo-Json $cur -Compress) +
      ',"error":"REAPER already uses another bridge; left unchanged. Pass -Force (reaper.mjs install --force) to switch to ' +
      ($want -replace '\\', '\\') + '"}')
    exit 6
  }
}

New-Item -ItemType Directory -Force (Join-Path $base 'inbox'), (Join-Path $base 'outbox') | Out-Null
$loader = @"
-- ClaudeBridge loader (generated by $PSCommandPath - do not edit)
-- Run from REAPER's Action list to start the bridge; run again to stop it.
CLAUDE_BRIDGE_ROOT = [[$want]]
dofile(CLAUDE_BRIDGE_ROOT .. "bridge.lua")
"@
[IO.File]::WriteAllText($loaderPath, $loader, (New-Object System.Text.UTF8Encoding $false))
# old standalone client from v1 lived here; the client is now send.ps1 next to this script
Remove-Item (Join-Path $base 'send.ps1') -ErrorAction SilentlyContinue
Write-Output ('{"ok":true,"installed":true,"current_root":' + (ConvertTo-Json $want -Compress) +
  ',"next":"node reaper.mjs restart (if the bridge is running) or start"}')
