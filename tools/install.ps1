# install.ps1 - point REAPER at this project's bridge.
# Writes a tiny loader to %APPDATA%\REAPER\Scripts\ClaudeBridge\ClaudeBridge.lua that runs
# <project>\bridge\bridge.lua, so editing the project files is all that's needed.
# Re-run after moving the project folder. Then: tools\bridge.ps1 restart
$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$bridgeDir = Join-Path $root 'bridge'
if (-not (Test-Path (Join-Path $bridgeDir 'bridge.lua'))) { throw "bridge.lua not found in $bridgeDir" }
$base = Join-Path $env:APPDATA 'REAPER\Scripts\ClaudeBridge'
New-Item -ItemType Directory -Force (Join-Path $base 'inbox'), (Join-Path $base 'outbox') | Out-Null
$loader = @"
-- ClaudeBridge loader (generated by $root\tools\install.ps1 - do not edit)
-- Run from REAPER's Action list to start the bridge; run again to stop it.
CLAUDE_BRIDGE_ROOT = [[$bridgeDir\]]
dofile(CLAUDE_BRIDGE_ROOT .. "bridge.lua")
"@
[IO.File]::WriteAllText((Join-Path $base 'ClaudeBridge.lua'), $loader, (New-Object System.Text.UTF8Encoding $false))
# old standalone client from v1 lived here; the client is now tools\send.ps1
Remove-Item (Join-Path $base 'send.ps1') -ErrorAction SilentlyContinue
Write-Output "installed loader -> $base\ClaudeBridge.lua (bridge root: $bridgeDir)"
Write-Output "next: powershell -NoProfile -ExecutionPolicy Bypass -File tools\bridge.ps1 restart"
